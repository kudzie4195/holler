#!/usr/bin/env node
/**
 * Builds lib/check/cells-data.ts from a cells measurement file (round 24: verdict-all-25mi.json, key "centre|trade").
 *
 *   node scripts/build-cells.mjs <path to verdict-all-25mi.json> [output path, default lib/check/cells-data.ts]
 *
 * The site never reads the measurement file at run time: this script copies what the gate needs into a checked-in module.
 * Per cell it keeps one value:
 *   'storm'    the cell's proposedWording is "storm-alerts" (and its state is not live): shown as limited, with the storm sentence;
 *   otherwise  the cell's `state` (live / limited / waitlist), which already includes the hand overrides.
 * Keys that are not a trade id of lib/signals/categories.ts (the "pw" pressure-washing rollup) are skipped from CELL_TABLE; the trade list
 * is checked by tests/check/cells-r24.test.ts.
 * Round 25: the "pw" rollup (a member with cleaning AND siding-gutters, the sign-up "Pressure washing" chip, lib/plan/composite-trades.ts)
 * is written to its own table, COMPOSITE_CELL_TABLE, keyed by the chip id, so /check answers pressure washing with the composite cell.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [, , src, out = 'lib/check/cells-data.ts'] = process.argv;
if (!src) {
  console.error('usage: node scripts/build-cells.mjs <verdict-all-25mi.json> [out]');
  process.exit(2);
}
const data = JSON.parse(readFileSync(src, 'utf8'));
const cats = readFileSync('lib/signals/categories.ts', 'utf8');
const tradeIds = [...cats.matchAll(/\{ id: '([a-z-]+)', label: '[^']*', group: '/g)].map((m) => m[1]);
const centres = [];
const table = {};
const notes = [];
/** Rollup key in the measurement -> composite chip id (lib/plan/composite-trades.ts). */
const COMPOSITES = { pw: 'pressure-washing' };
const composite = {};
for (const [key, cell] of Object.entries(data)) {
  const [centre, trade] = key.split('|');
  if (COMPOSITES[trade]) {
    const state = cell.state;
    if (!['live', 'limited', 'waitlist'].includes(state)) throw new Error(`bad state ${key}: ${state}`);
    (composite[centre] ??= {})[COMPOSITES[trade]] = cell.proposedWording === 'storm-alerts' && state !== 'live' ? 'storm' : state;
    continue;
  }
  if (!tradeIds.includes(trade)) continue;
  if (!centres.includes(centre)) centres.push(centre);
  const state = cell.state;
  if (!['live', 'limited', 'waitlist'].includes(state)) throw new Error(`bad state ${key}: ${state}`);
  const v = cell.proposedWording === 'storm-alerts' && state !== 'live' ? 'storm' : state;
  (table[centre] ??= {})[trade] = v;
  if (cell.stateNote) notes.push([key, cell.engineState, state, cell.stateNote]);
}
for (const c of centres) for (const t of tradeIds) if (!table[c][t]) throw new Error(`missing cell ${c}|${t}`);
for (const c of centres) for (const id of Object.values(COMPOSITES)) if (!composite[c]?.[id]) throw new Error(`missing composite cell ${c}|${id}`);
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
let ts = `// GENERATED by scripts/build-cells.mjs from the round 24 cells measurement (verdict-all-25mi.json). Do not edit by hand:
// rerun the script on a new measurement and commit the result.
// ${centres.length} centres x ${tradeIds.length} trades = ${centres.length * tradeIds.length} cells, measured over 14 days (2026-11-09 to 2026-11-23),
// inside 25 miles of each centre. Value per cell: the measured \`state\` (hand overrides included), or 'storm' where the cell's
// proposed wording is storm alerts.
export type CellValue = 'live' | 'limited' | 'waitlist' | 'storm';

/** Every trade id the measurement covered, in lib/signals/categories.ts order. */
export const MEASURED_TRADE_IDS: readonly string[] = [${tradeIds.map(q).join(', ')}];

/** Every measured centre id, in the order of the measurement. */
export const MEASURED_CENTRE_IDS: readonly string[] = [${centres.map(q).join(', ')}];

export const CELL_TABLE: Readonly<Record<string, Readonly<Record<string, CellValue>>>> = {
`;
for (const c of centres) {
  ts += `  ${q(c)}: {\n`;
  for (const t of tradeIds) ts += `    ${q(t)}: ${q(table[c][t])},\n`;
  ts += '  },\n';
}
ts += `};

/**
 * Round 25: composite cells from the measurement's rollups, keyed by the composite chip id (lib/plan/composite-trades.ts). "pressure-washing" is a
 * member with cleaning AND siding-gutters, measured as one member (its cards are the union of both trades' cards).
 */
export const COMPOSITE_CELL_TABLE: Readonly<Record<string, Readonly<Record<string, CellValue>>>> = {
${centres.map((c) => `  ${q(c)}: { ${Object.entries(composite[c] ?? {}).map(([k, v]) => `${q(k)}: ${q(v)}`).join(', ')} },`).join('\n')}
};

/** The hand overrides the measurement carries (engine state -> state), for the record. Not read by the gate. */
export const CELL_OVERRIDES: readonly { cell: string; engine: string; state: string; note: string }[] = [
${notes.map(([k, e, s, n]) => `  { cell: ${q(k)}, engine: ${q(e)}, state: ${q(s)}, note: ${q(n)} },`).join('\n')}
];
`;
writeFileSync(out, ts);
const counts = {};
for (const c of centres) for (const t of tradeIds) counts[table[c][t]] = (counts[table[c][t]] ?? 0) + 1;
console.log(`wrote ${out}: ${centres.length} centres, ${tradeIds.length} trades`, counts);
