/**
 * Honest coverage, per PLACE and per TRADE. Round 24: the one function every public surface asks (coverageFor).
 *
 * Three states, nothing else:
 *   live      the feed is worth paying for here: the trial offer shows.
 *   limited   sign-up is still offered, under a line that says in plain words what Holler has: few records, not measured here yet, or
 *             storm alerts only (they arrive when a storm hits, and there may be few or none between storms).
 *   waitlist  nothing a member could act on: no price, no trial, no link to sign-up. The waitlist card is the whole answer.
 *
 * WHERE THE TABLE COMES FROM. lib/check/cells-data.ts, generated by scripts/build-cells.mjs from the round 24 measurement of all 41 trades
 * in 22 centres (902 cells, 14 days of live records inside 25 miles of each centre, counting only cards an owner could act on). The
 * thresholds are the owner's: live = 5 or more actionable cards a week AND 10 or more distinct places in 14 days; limited = 1 or more a
 * week; otherwise waitlist. The file's `state` already carries the 12 hand overrides. A cell whose proposed wording is storm alerts is
 * stored as 'storm' and answered as limited, never live.
 *
 * THE RULES, in order (coverageFor):
 *   1. no local source for the place (lib/check/coverage.ts isServedZip)                     -> waitlist
 *   2. a trade that is live in no centre and has no storm cell (tradeSignupClosed): sign-up
 *      does not take it, so no page may offer it                                              -> waitlist, everywhere
 *   3. no measured centre within 25 miles                                                     -> limited, measured: false
 *   4. the nearest measured centre's cell: live / limited / waitlist; storm                   -> limited, storm: true
 * So no trade is ever live without a measured live cell (tests/check/cells-r24.test.ts checks every trade at every centre).
 *
 * Marketing is a separate decision and is NOT encoded here: this table tells each visitor the truth about their own cell.
 */
export type CoverageState = 'live' | 'limited' | 'waitlist';

export interface Coverage {
  state: CoverageState;
  /** The measured centre the answer came from, or null. */
  centre: string | null;
  /** False when no measured centre is within 25 miles (or the place has no local source). The page then says it was not measured. */
  measured: boolean;
  /** True for a storm-alerts cell: limited, plus the one sentence about storms. */
  storm: boolean;
  /** True when sign-up does not take this trade anywhere (tradeSignupClosed). */
  closed: boolean;
}

