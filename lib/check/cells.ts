/** Every trade the measurement covered: all 41. */
export const MEASURED_TRADES: readonly string[] = MEASURED_TRADE_IDS;

export interface Centre {
  id: string;
  lat: number;
  lon: number;
}

let centres: Centre[] | null = null;

/** The 22 measured centres with their coordinates, memoised. A centre whose place cannot be resolved is skipped (tests check none is). */
export function measuredCentres(): readonly Centre[] {
  if (centres) return centres;
  const out: Centre[] = [];
  for (const c of CENTRE_SOURCE) {
    if (!MEASURED_CENTRE_IDS.includes(c.id)) continue;
    const point = c.metro ? METROS.find((m) => m.id === c.metro)?.center : c.city ? cityBySlug(c.city) : null;
    if (point) out.push({ id: c.id, lat: point.lat, lon: point.lon });
  }
  centres = out;
  return out;
}

/** The measured centre nearest this point inside `maxMi`, or null. */
export function nearestMeasuredCentre(lat: number, lon: number, maxMi: number = CHECK_RADIUS_MI): Centre | null {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return null;
  let best: Centre | null = null;
  let bestD = Infinity;
  for (const c of measuredCentres()) {
    const d = haversineMi(lat, lon, c.lat, c.lon);
    if (d <= maxMi && d < bestD) {
      best = c;
      bestD = d;
    }
  }
  return best;
}

/** The stored value of one cell ('live', 'limited', 'waitlist' or 'storm'), or null when the centre or the trade was never measured. */
export function measuredCell(centreId: string, trade: string): CellValue | null {
  return CELL_TABLE[centreId]?.[trade] ?? null;
}

/** True when at least one measured centre has this trade live. */
export function tradeLiveAnywhere(trade: string): boolean {
  return MEASURED_CENTRE_IDS.some((c) => CELL_TABLE[c]?.[trade] === 'live');
}

/** True when at least one measured centre has a storm-alerts cell for this trade. */
export function tradeHasStormCells(trade: string): boolean {
  return MEASURED_CENTRE_IDS.some((c) => CELL_TABLE[c]?.[trade] === 'storm');
}

/**
 * Sign-up does not take this trade: it is live in no measured centre and has no storm-alerts cell. Derived from the table, never typed.
 * Members who already saved one keep it (lib/auth/profile.ts); the trade page keeps its content but offers the check and the list only.
 * A trade id that is not in the table at all is closed too.
 */
export function tradeSignupClosed(trade: string): boolean {
  if (!MEASURED_TRADE_IDS.includes(trade)) return true;
  return !tradeLiveAnywhere(trade) && !tradeHasStormCells(trade);
}

/** Every closed trade id, in category order. */
export function signupClosedTrades(): string[] {
  return MEASURED_TRADE_IDS.filter((t) => tradeSignupClosed(t));
}

/**
 * What this place and this trade get. `served` is the whole-ZIP answer (lib/check/coverage.ts isServedZip), passed in so this module
 * stays free of the feed catalogue and can be tested on its own. The rules are in the comment at the top of this file.
 */
export function coverageFor(place: { lat: number; lon: number }, trade: string, served: boolean): Coverage {
  const closed = tradeSignupClosed(trade);
  if (!served) return { state: 'waitlist', centre: null, measured: false, storm: false, closed };
  const centre = nearestMeasuredCentre(place.lat, place.lon);
  if (closed) return { state: 'waitlist', centre: centre?.id ?? null, measured: centre !== null, storm: false, closed };
  if (!centre) return { state: 'limited', centre: null, measured: false, storm: false, closed };
  const cell = measuredCell(centre.id, trade);
  if (cell === 'storm') return { state: 'limited', centre: centre.id, measured: true, storm: true, closed };
  return { state: cell ?? 'waitlist', centre: centre.id, measured: true, storm: false, closed };
}

/**
 * The answer for a whole place (a city page): the best answer any trade sign-up takes gets there, through coverageFor, so the city page
 * and the ZIP check can never disagree. `live` lists the trades that are live here, `limited` the ones that are limited.
 */
export function placeCoverage(
  place: { lat: number; lon: number },
  served: boolean,
): { state: CoverageState; measured: boolean; live: string[]; limited: string[] } {
  const live: string[] = [];
  const limited: string[] = [];
  let measured = false;
  for (const trade of MEASURED_TRADE_IDS) {
    const c = coverageFor(place, trade, served);
    if (c.measured) measured = true;
    if (c.state === 'live') live.push(trade);
    else if (c.state === 'limited') limited.push(trade);
  }
  const state: CoverageState = live.length ? 'live' : limited.length ? 'limited' : 'waitlist';
  return { state, measured, live, limited };
}

/** Is this place worth the full trial offer for any trade? True only when some trade is live here (placeCoverage). */
export function anyTradeLive(place: { lat: number; lon: number }, served: boolean): boolean {
  return placeCoverage(place, served).state === 'live';
}
